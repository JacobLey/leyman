import type { StandardJSONSchemaV1, StandardSchemaV1 } from '@standard-schema/spec';
import type { Options as AjvOptions, ErrorObject } from 'ajv/dist/2020.js';
import type { JsonSchema, Schema } from 'juniper';
import { Ajv2020 } from 'ajv/dist/2020.js';
import ajvFormats from 'ajv-formats';
import { defaultImport } from 'default-import';
import { isSchema } from 'juniper';

const addFormats = defaultImport(ajvFormats);

export interface JuniperValidator<T> extends StandardSchemaV1<T>, StandardJSONSchemaV1<T> {
    // eslint-disable-next-line @typescript-eslint/naming-convention -- Both interfaces declare `~standard`, so it must be declared as their combination
    readonly '~standard': StandardJSONSchemaV1.Props<T> & StandardSchemaV1.Props<T>;
    is: (x: unknown) => x is T;
    assert: (x: unknown) => asserts x is T;
    /**
     * Shorthand for StandardSchema
     */
    validate: (value: unknown) => StandardSchemaV1.Result<T>;
}

// Draft 2020-12 keywords whose values hold subschemas, as one subschema, a list, or a map
const subschemaKeywords = new Set([
    'additionalProperties',
    'contains',
    'else',
    'if',
    'items',
    'not',
    'propertyNames',
    'then',
    'unevaluatedItems',
    'unevaluatedProperties',
]);
const subschemaListKeywords = new Set(['allOf', 'anyOf', 'oneOf', 'prefixItems']);
const subschemaMapKeywords = new Set([
    '$defs',
    'dependentSchemas',
    'patternProperties',
    'properties',
]);

/**
 * Juniper forbids `.metadata()` from using JSON Schema keywords, so any keyword Ajv doesn't know
 * is metadata. Register each as an annotation so strict mode accepts it.
 *
 * @param ajv - Ajv instance to register keywords on
 * @param schema - JSON Schema generated by Juniper
 */
const addMetadataKeywords = (ajv: Ajv2020, schema: unknown): void => {
    // Boolean schemas
    if (typeof schema !== 'object' || schema === null) {
        return;
    }
    for (const [key, value] of Object.entries(schema)) {
        if (subschemaKeywords.has(key)) {
            addMetadataKeywords(ajv, value);
        } else if (subschemaListKeywords.has(key)) {
            for (const subschema of value as unknown[]) {
                addMetadataKeywords(ajv, subschema);
            }
        } else if (subschemaMapKeywords.has(key)) {
            for (const subschema of Object.values(value as object)) {
                addMetadataKeywords(ajv, subschema);
            }
        } else if (ajv.RULES.keywords[key] !== true) {
            ajv.addVocabulary([key]);
        }
    }
};

/**
 * Convert Ajv's `instancePath` (a JSON Pointer) to a Standard Schema path.
 * Array indices become numbers, and a missing or extra property is placed at that property
 * rather than the object that lacks (or has) it.
 *
 * @param error - Ajv error
 * @param value - validated value, used to tell array indices from object keys
 * @returns path to the invalid value
 */
const toPath = (error: ErrorObject, value: unknown): PropertyKey[] => {
    const path: PropertyKey[] = [];
    if (error.instancePath) {
        let current = value;
        for (const segment of error.instancePath.slice(1).split('/')) {
            const key = segment.replaceAll('~1', '/').replaceAll('~0', '~');
            if (Array.isArray(current)) {
                const index = Number(key);
                path.push(index);
                current = current[index];
            } else {
                path.push(key);
                current = (current as Record<string, unknown>)[key];
            }
        }
    }
    // Missing and extra properties are placed at that property
    const { params } = error as ErrorObject<string, Record<string, unknown>>;
    const property =
        params.missingProperty ?? params.additionalProperty ?? params.unevaluatedProperty;
    if (typeof property === 'string') {
        path.push(property);
    }
    return path;
};

export const makeValidator = <T>(
    schema: JsonSchema<T> | Schema<T>,
    options?: Omit<AjvOptions, 'jsPropertySyntax' | 'strict'>
): JuniperValidator<T> => {
    const json = isSchema(schema) ? schema.toJSON({ schema: true }) : schema;
    // eslint-disable-next-line @typescript-eslint/no-deprecated, sonarjs/deprecation -- Dropped (even for untyped callers) so `instancePath`, which issue paths are parsed from, stays a JSON Pointer
    const { jsPropertySyntax, ...ajvOptions }: AjvOptions = { ...options };
    // Standard formats (`email`, `uuid`, `date-time`, ...), which strict mode otherwise rejects as unknown.
    // `discriminator` is emitted by Juniper's discriminated `oneOf`.
    // `strictTuples` rejects open tuples (`prefixItem()` on an array with no `maxItems`), which Juniper supports
    const ajv = addFormats(
        new Ajv2020({ discriminator: true, strictTuples: false, ...ajvOptions, strict: true })
    );
    if (isSchema(schema)) {
        addMetadataKeywords(ajv, json);
    }
    const validator = ajv.compile<T>(json);

    const validate = (value: unknown): StandardSchemaV1.Result<T> => {
        if (validator(value)) {
            return {
                value,
            };
        }
        return {
            issues: validator.errors!.map(error => ({
                ...error,
                // Ajv omits messages with `messages: false`
                message: error.message ?? `must pass "${error.keyword}" keyword validation`,
                path: toPath(error, value),
            })),
        };
    };

    const jsonSchema: StandardJSONSchemaV1.Converter = isSchema(schema)
        ? schema['~standard'].jsonSchema
        : {
              input: ({ target }) => {
                  if (target === 'draft-2020-12') {
                      return schema;
                  }
                  throw new Error(`JSON Schema target: "${target}" not supported`);
              },
              output: standard => jsonSchema.input(standard),
          };

    return {
        is: x => validator(x),
        assert: x => {
            if (validator(x)) {
                return;
            }
            throw new Error('Value does not match schema', { cause: validator.errors });
        },
        '~standard': {
            version: 1,
            vendor: 'juniper',
            validate,
            jsonSchema,
        },
        validate,
    };
};

export type ValidatorType<T extends JuniperValidator<unknown>> = T extends {
    is: (x: unknown) => x is infer V;
}
    ? V
    : never;
export type AssertionType<T extends JuniperValidator<unknown>> = T['assert'];
