// Package golang writes the named types of a converted schema as Go source.
//
// Go can't express every type TypeScript can, so some types are wider than genever's TypeScript (a pattern is a
// string, an enum's constants don't restrict its type), and some need code to read and write their JSON: unions,
// tuples and objects with properties beyond those declared. That code only decides which Go value holds a JSON value,
// and fails only when none can. It never checks a constraint such as `pattern` or `minimum`.
package golang

import (
	"fmt"
	"go/format"
	"slices"
	"sort"
	"strings"

	"github.com/JacobLey/leyman/apps/genever/go/internal/convert"
	"github.com/JacobLey/leyman/apps/genever/go/internal/model"
)

// Header is the first line of every generated file, in the form Go tools recognize as generated code.
const Header = "// Code generated by genever. DO NOT EDIT."

// Names a struct's fields can't have, as its methods have them.
//
//nolint:gochecknoglobals // Never changed
var methodNames = []string{"MarshalJSON", "UnmarshalJSON", "AdditionalProperties", "Rest"}

type generator struct {
	named   map[string]*model.Type
	names   *namespace
	helpers map[string]bool
	imports map[string]bool
	// aliases are named types written as aliases, which can't have methods of their own.
	aliases map[string]bool
	// defined are types this file defines, which can have methods.
	defined map[string]bool
	// markers are the marker methods of union variants, by type.
	markers map[string][]string
	// resolving guards against following a cycle of references.
	resolving map[string]bool
	decls     []string
}

// Generate writes Go source for the named types, in package pkg, formatted as gofmt does.
func Generate(types []convert.NamedType, pkg string) ([]byte, error) {
	gen := &generator{
		named:     map[string]*model.Type{},
		names:     newNamespace(helperOptional, helperNull, helperNever),
		helpers:   map[string]bool{},
		imports:   map[string]bool{},
		aliases:   map[string]bool{},
		defined:   map[string]bool{},
		markers:   map[string][]string{},
		resolving: map[string]bool{},
		decls:     nil,
	}

	for _, named := range types {
		gen.named[named.Name] = named.Type
		gen.names.used[named.Name] = true
	}

	for _, named := range types {
		gen.aliases[named.Name] = gen.isAliasForm(named.Type)
	}

	for _, named := range types {
		gen.declareNamed(named.Name, named.Doc, named.Type)
	}

	source := gen.file(pkg)

	formatted, err := format.Source([]byte(source))
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w\n%s", err, source)
	}

	return formatted, nil
}

// isAliasForm reports whether a named type is written as an alias, as declareNamed and declareBasic write it.
func (g *generator) isAliasForm(typ *model.Type) bool {
	_, nullable := splitNull(typ)
	if nullable || typ.Kind == model.KindReference || typ.Is(model.Unknown) || typ.Is(model.Never) ||
		typ.Is(model.Null) {
		return true
	}

	// An intersection Go writes as the type of its class, which is json.RawMessage or Null for these classes
	class := g.classOf(typ)

	return typ.Kind == model.KindIntersection && !g.isObjectish(typ) &&
		(class == model.ClassNone || class == model.ClassNull)
}

// splitNull separates null from the other members of a union.
func splitNull(typ *model.Type) (*model.Type, bool) {
	if typ.Kind != model.KindUnion || !slices.ContainsFunc(typ.Members, isNull) {
		return typ, false
	}

	return model.Union(slices.DeleteFunc(slices.Clone(typ.Members), isNull)...), true
}

func isNull(typ *model.Type) bool {
	return typ.Is(model.Null)
}

func (g *generator) file(pkg string) string {
	var body strings.Builder

	for _, decl := range g.decls {
		body.WriteString(decl)
		body.WriteString("\n\n")
	}

	for _, name := range sortedKeys(g.markers) {
		for _, method := range g.markers[name] {
			fmt.Fprintf(&body, "func (%s) %s() {}\n\n", name, method)
		}
	}

	g.addHelperImports()

	for _, name := range sortedKeys(g.helpers) {
		body.WriteString(helpers[name].code)
		body.WriteString("\n\n")
	}

	var file strings.Builder

	file.WriteString(Header + "\n\npackage " + pkg + "\n\n")

	if len(g.imports) > 0 {
		file.WriteString("import (\n")

		for _, path := range sortedKeys(g.imports) {
			fmt.Fprintf(&file, "\t%q\n", path)
		}

		file.WriteString(")\n\n")
	}

	file.WriteString(body.String())

	return file.String()
}

func (g *generator) addHelperImports() {
	for name := range g.helpers {
		for _, path := range helpers[name].imports {
			g.imports[path] = true
		}
	}
}

func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}

	sort.Strings(keys)

	return keys
}

func (g *generator) use(helperName string) string {
	g.helpers[helperName] = true

	return helperName
}

func (g *generator) json() string {
	g.imports["encoding/json"] = true

	return "json"
}

// reserveDecl takes a place in the file for a declaration written later, so a type comes before the types made for
// its parts.
func (g *generator) reserveDecl() func(string) {
	index := len(g.decls)
	g.decls = append(g.decls, "")

	return func(decl string) {
		g.decls[index] = decl
	}
}

// resolve follows references to the named type they name.
func (g *generator) resolve(typ *model.Type) *model.Type {
	seen := map[string]bool{}
	for typ.Kind == model.KindReference && !seen[typ.Name] {
		seen[typ.Name] = true
		typ = g.named[typ.Name]
	}

	return typ
}

// includesNull reports whether a type's values include null, through references too.
func (g *generator) includesNull(typ *model.Type) bool {
	resolved := g.resolve(typ)
	_, nullable := splitNull(resolved)

	return nullable || resolved.Is(model.Null) || resolved.Is(model.Unknown)
}

// declareNamed writes a named type of the document.
func (g *generator) declareNamed(name string, doc *model.Doc, typ *model.Type) {
	if rest, nullable := splitNull(typ); nullable {
		write := g.reserveDecl()
		inner := g.goType(rest, name+"Value")
		write(docComment(doc) + fmt.Sprintf("type %s = *%s", name, inner))

		return
	}

	switch {
	case typ.Is(model.Unknown):
		g.decls = append(g.decls, docComment(doc)+fmt.Sprintf("type %s = %s.RawMessage", name, g.json()))
	case typ.Is(model.Never) || typ.Is(model.Null):
		helperName := helperNever
		if typ.Is(model.Null) {
			helperName = helperNull
		}

		g.decls = append(g.decls, docComment(doc)+fmt.Sprintf("type %s = %s", name, g.use(helperName)))
	case typ.Kind == model.KindReference:
		g.decls = append(g.decls, docComment(doc)+fmt.Sprintf("type %s = %s", name, typ.Name))
	default:
		g.declareDefined(name, doc, typ)
	}
}

// declareDefined writes a type that may have methods: a struct, enum, union, tuple, or a defined basic type.
func (g *generator) declareDefined(name string, doc *model.Doc, typ *model.Type) {
	g.defined[name] = true

	switch {
	case typ.Kind == model.KindObject || (typ.Kind == model.KindIntersection && g.isObjectish(typ)):
		properties, index := g.shape(typ)
		g.declareObject(name, doc, properties, index)
	case typ.Kind == model.KindTuple:
		g.declareTuple(name, doc, typ)
	case typ.Kind == model.KindUnion || isEnum(typ):
		g.declareUnion(name, doc, typ)
	default:
		g.declareBasic(name, doc, typ)
	}
}

// declareBasic writes a type of another Go type: defined, or an alias where a defined type would lose the methods of
// json.RawMessage or of the helpers.
func (g *generator) declareBasic(name string, doc *model.Doc, typ *model.Type) {
	write := g.reserveDecl()
	goType := g.goType(typ, name)

	operator := " "
	if goType == "json.RawMessage" || goType == helperNull || goType == helperNever {
		operator = " = "
		g.aliases[name] = true
		delete(g.defined, name)
	}

	write(docComment(doc) + "type " + name + operator + goType)
}

// isEnum reports whether a type is a string literal, which is written as a type with a constant.
func isEnum(typ *model.Type) bool {
	return typ.Kind == model.KindLiteral && typ.Class() == model.ClassString
}

// goType returns the Go type of a value, declaring a named type for it, named after hint, when it needs one.
//
//nolint:cyclop // One case per kind of type
func (g *generator) goType(typ *model.Type, hint string) string {
	// nil is null
	if rest, nullable := splitNull(typ); nullable {
		return "*" + g.goType(rest, hint)
	}

	switch typ.Kind {
	case model.KindKeyword:
		return g.keywordType(typ.Keyword)
	case model.KindLiteral:
		if isEnum(typ) {
			return g.declare(hint, typ)
		}

		return g.literalType(typ)
	case model.KindTemplate:
		return goString
	case model.KindArray:
		return "[]" + g.goType(typ.Element, hint+"Item")
	case model.KindReference:
		return typ.Name
	case model.KindObject:
		if len(typ.Properties) == 0 && len(typ.Index) > 0 && !g.indexValue(typ.Index).Is(model.Never) {
			return "map[string]" + g.goType(g.indexValue(typ.Index), hint+"Value")
		}

		return g.declare(hint, typ)
	case model.KindTuple, model.KindUnion:
		return g.declare(hint, typ)
	case model.KindIntersection:
		if g.isObjectish(typ) {
			return g.declare(hint, typ)
		}
	}

	return g.classType(typ)
}

// declare declares a named type, with a unique name from hint, and returns the name.
func (g *generator) declare(hint string, typ *model.Type) string {
	name := g.names.reserve(hint)
	g.declareDefined(name, nil, typ)

	return name
}

func (g *generator) keywordType(keyword model.Keyword) string {
	switch keyword {
	case model.Never:
		return g.use(helperNever)
	case model.Boolean:
		return goBool
	case model.Null:
		return g.use(helperNull)
	case model.Number:
		return goFloat
	case model.Integer:
		return "int64"
	case model.String:
		return goString
	case model.AnyObject:
		return "map[string]" + g.json() + ".RawMessage"
	case model.Unknown:
	}

	return g.json() + ".RawMessage"
}

func (g *generator) literalType(typ *model.Type) string {
	if typ.Class() == model.ClassBoolean {
		return goBool
	}

	return goFloat
}

// classType is the type of the values of a type Go can't write as it is, such as an intersection of patterns: the type
// of every value of its class.
func (g *generator) classType(typ *model.Type) string {
	switch g.classOf(typ) {
	case model.ClassString:
		return goString
	case model.ClassNumber:
		return goFloat
	case model.ClassBoolean:
		return goBool
	case model.ClassArray:
		return "[]" + g.json() + ".RawMessage"
	case model.ClassNull:
		return g.use(helperNull)
	// An object type is objectish, so declared as a struct instead
	case model.ClassObject, model.ClassNone:
	}

	return g.json() + ".RawMessage"
}

// classOf is the class of a type's values, through intersections too: the class every member shares.
func (g *generator) classOf(typ *model.Type) model.Class {
	if typ.Kind != model.KindIntersection {
		return g.resolve(typ).Class()
	}

	class := model.ClassNone
	for _, member := range typ.Members {
		if memberClass := g.classOf(member); memberClass != model.ClassNone {
			class = memberClass
		}
	}

	return class
}

// isObjectish reports whether every value of a type is an object, so its parts can be merged into one struct.
func (g *generator) isObjectish(typ *model.Type) bool {
	switch typ.Kind {
	case model.KindObject:
		return true
	case model.KindKeyword:
		return typ.Is(model.AnyObject)
	case model.KindReference:
		if g.resolving[typ.Name] {
			return true
		}

		g.resolving[typ.Name] = true
		defer delete(g.resolving, typ.Name)

		return g.isObjectish(g.named[typ.Name])
	case model.KindIntersection, model.KindUnion:
		for _, member := range typ.Members {
			if !g.isObjectish(member) {
				return false
			}
		}

		return true
	case model.KindTuple, model.KindArray, model.KindLiteral, model.KindTemplate:
	}

	return false
}

// shape merges the parts of an object type into the properties and index signatures of one struct. A property from
// only some members of a union is optional, as it may be absent.
func (g *generator) shape(typ *model.Type) ([]model.Property, []model.Index) {
	merged := &shaper{g: g, properties: nil, index: nil, positions: map[string]int{}}
	merged.visit(typ, false)

	return merged.properties, merged.index
}

// A shaper collects the properties and index signatures of the parts of an object type.
type shaper struct {
	g          *generator
	positions  map[string]int
	properties []model.Property
	index      []model.Index
}

// add adds a property, intersected with a property of the same name if there is one.
func (s *shaper) add(property model.Property, optional bool) {
	property.Optional = property.Optional || optional
	if position, ok := s.positions[property.Name]; ok {
		existing := s.properties[position]
		existing.Optional = existing.Optional && property.Optional
		existing.Type = model.Intersection(existing.Type, property.Type)
		s.properties[position] = existing

		return
	}

	s.positions[property.Name] = len(s.properties)
	s.properties = append(s.properties, property)
}

// visitReference visits a named type, unless already within it.
func (s *shaper) visitReference(name string, optional bool) {
	if !s.g.resolving[name] {
		s.g.resolving[name] = true
		s.visit(s.g.named[name], optional)
		delete(s.g.resolving, name)
	}
}

// visitUnion adds the properties of the members of a union: a property's type is its types in each member together,
// and it is optional unless every member requires it.
func (s *shaper) visitUnion(members []*model.Type, optional bool) {
	shapes := make([]*shaper, len(members))
	for i, member := range members {
		shapes[i] = &shaper{g: s.g, properties: nil, index: nil, positions: map[string]int{}}
		shapes[i].visit(member, false)
		s.index = append(s.index, shapes[i].index...)
	}

	for _, member := range shapes {
		for _, property := range member.properties {
			if _, done := s.positions[property.Name]; done {
				continue
			}

			typesOf := []*model.Type{}
			required := !optional

			for _, other := range shapes {
				position, ok := other.positions[property.Name]
				if !ok {
					required = false

					continue
				}

				typesOf = append(typesOf, other.properties[position].Type)
				required = required && !other.properties[position].Optional
			}

			property.Type = model.Union(typesOf...)
			s.add(property, !required)
		}
	}
}

// visit adds the properties of a part, all optional if the part may be absent.
func (s *shaper) visit(part *model.Type, optional bool) {
	switch part.Kind {
	case model.KindObject:
		for _, property := range part.Properties {
			s.add(property, optional)
		}

		s.index = append(s.index, part.Index...)
	case model.KindReference:
		s.visitReference(part.Name, optional)
	case model.KindIntersection:
		for _, member := range part.Members {
			s.visit(member, optional)
		}
	case model.KindUnion:
		s.visitUnion(part.Members, optional)
	case model.KindKeyword:
		// Any object
		s.index = append(s.index, model.Index{Key: model.StringType, Value: model.UnknownType})
	case model.KindTuple, model.KindArray, model.KindLiteral, model.KindTemplate:
	}
}

// indexValue is the type of the values of keys no property declares: of every index signature.
func (g *generator) indexValue(index []model.Index) *model.Type {
	values := make([]*model.Type, len(index))
	for i, signature := range index {
		values[i] = signature.Value
	}

	return model.Union(values...)
}

// A field of a struct.
type field struct {
	name    string
	goType  string
	jsonKey string
	// omit is the tag's option for an absent value: omitempty, omitzero, or none for a required property.
	omit string
	// presence is an expression of the struct `s` that is true when an optional value is present.
	presence string
	doc      *model.Doc
}

// fieldOf returns the field of a property or tuple item: required, it is the type (a pointer if it may be null);
// optional, a pointer, or Optional where a pointer can't tell an absent value from null.
func (g *generator) fieldOf(name, jsonKey string, typ *model.Type, optional bool, hint string) field {
	result := field{name: name, goType: "", jsonKey: jsonKey, omit: "", presence: "", doc: nil}

	switch {
	case typ.Is(model.Unknown):
		result.goType = g.goType(typ, hint)
		if optional {
			result.omit = "omitempty"
			result.presence = "s." + name + " != nil"
		}
	case !optional:
		result.goType = g.goType(typ, hint)
	case g.includesNull(typ):
		result.goType = fmt.Sprintf("%s[%s]", g.use(helperOptional), g.goType(typ, hint))
		result.omit = "omitzero"
		result.presence = "s." + name + ".Set"
	default:
		result.goType = "*" + g.goType(typ, hint)
		result.omit = "omitempty"
		result.presence = "s." + name + " != nil"
	}

	return result
}

func (g *generator) declareObject(name string, doc *model.Doc, properties []model.Property, index []model.Index) {
	write := g.reserveDecl()
	fieldNames := newNamespace(methodNames...)

	var fields []field

	for _, property := range properties {
		if property.Optional && property.Type.Is(model.Never) {
			// Never present
			continue
		}

		fieldName := fieldNames.reserve(Identifier(property.Name, "Field"))
		result := g.fieldOf(fieldName, property.Name, property.Type, property.Optional, name+fieldName)
		result.doc = property.Doc
		fields = append(fields, result)
	}

	extra := g.indexValue(index)
	hasExtra := len(index) > 0 && !extra.Is(model.Never)

	var decl strings.Builder

	decl.WriteString(docComment(doc))
	fmt.Fprintf(&decl, "type %s struct {\n", name)

	for _, result := range fields {
		decl.WriteString(indent(docComment(result.doc)))

		options := ""
		if result.omit != "" {
			options = "," + result.omit
		}

		fmt.Fprintf(&decl, "\t%s %s `json:%q`\n", result.name, result.goType, result.jsonKey+options)
	}

	if hasExtra {
		extraType := g.goType(extra, name+"Value")

		decl.WriteString("\t// AdditionalProperties are the properties no field declares.\n")
		fmt.Fprintf(&decl, "\tAdditionalProperties map[string]%s `json:\"-\"`\n}\n\n", extraType)
		decl.WriteString(g.extraMethods(name, extraType, fields))
	} else {
		decl.WriteString("}")
	}

	write(decl.String())
}

func (g *generator) extraMethods(name, extraType string, fields []field) string {
	known := make([]string, len(fields))
	for i, result := range fields {
		known[i] = fmt.Sprintf("%q", result.jsonKey)
	}

	encoding := g.json()

	return fmt.Sprintf(`// MarshalJSON writes the fields, then the additional properties.
func (s %[1]s) MarshalJSON() ([]byte, error) {
	type plain %[1]s
	data, err := %[2]s.Marshal(plain(s))
	if err != nil {
		return nil, err
	}
	return %[3]s(data, s.AdditionalProperties)
}

// UnmarshalJSON reads the fields, and the other properties as additional properties.
func (s *%[1]s) UnmarshalJSON(data []byte) error {
	type plain %[1]s
	var value plain
	if err := %[2]s.Unmarshal(data, &value); err != nil {
		return err
	}
	extra, err := %[4]s[%[5]s](data%[6]s)
	if err != nil {
		return err
	}
	value.AdditionalProperties = extra
	*s = %[1]s(value)
	return nil
}`, name, encoding, g.use(helperWith), g.use(helperExtra), extraType, joinPrefixed(known))
}

func joinPrefixed(items []string) string {
	if len(items) == 0 {
		return ""
	}

	return ", " + strings.Join(items, ", ")
}

func (g *generator) declareTuple(name string, doc *model.Doc, typ *model.Type) {
	write := g.reserveDecl()

	fields := make([]field, len(typ.Elements))
	required := 0

	for i, element := range typ.Elements {
		fieldName := fmt.Sprintf("Item%d", i)
		fields[i] = g.fieldOf(fieldName, "", element.Type, element.Optional, name+fieldName)

		if !element.Optional {
			required = i + 1
		}
	}

	restType := ""
	maxItems := len(typ.Elements)

	if typ.Rest != nil {
		restType = g.goType(typ.Rest, name+"Item")
		maxItems = -1
	}

	var decl strings.Builder

	decl.WriteString(docComment(doc))
	fmt.Fprintf(&decl, "type %s struct {\n", name)

	for _, result := range fields {
		fmt.Fprintf(&decl, "\t%s %s\n", result.name, result.goType)
	}

	if restType != "" {
		fmt.Fprintf(&decl, "\t// Rest are the items after the others.\n\tRest []%s\n", restType)
	}

	decl.WriteString("}\n\n")
	decl.WriteString(g.tupleMarshal(name, fields, restType != ""))
	decl.WriteString("\n\n")
	decl.WriteString(g.tupleUnmarshal(name, fields, restType, required, maxItems))
	write(decl.String())
}

func (g *generator) tupleMarshal(name string, fields []field, hasRest bool) string {
	var body strings.Builder

	fmt.Fprintf(&body, "// MarshalJSON writes the items as an array.\nfunc (s %s) MarshalJSON() ([]byte, error) {\n", name)
	body.WriteString("\titems := []any{}\n")

	for _, result := range fields {
		if result.presence != "" {
			fmt.Fprintf(&body, "\tif !(%s) {\n\t\treturn %s.Marshal(items)\n\t}\n", result.presence, g.json())
		}

		fmt.Fprintf(&body, "\titems = append(items, s.%s)\n", result.name)
	}

	if hasRest {
		body.WriteString("\tfor _, item := range s.Rest {\n\t\titems = append(items, item)\n\t}\n")
	}

	fmt.Fprintf(&body, "\treturn %s.Marshal(items)\n}", g.json())

	return body.String()
}

func (g *generator) tupleUnmarshal(name string, fields []field, restType string, required, maxItems int) string {
	var body strings.Builder

	fmt.Fprintf(&body, "// UnmarshalJSON reads the items of an array.\nfunc (s *%s) UnmarshalJSON(data []byte) error {\n", name)
	fmt.Fprintf(&body, "\titems, err := %s(data, %d, %d)\n\tif err != nil {\n\t\treturn err\n\t}\n",
		g.use(helperTuple), required, maxItems)
	fmt.Fprintf(&body, "\t*s = %s{}\n", name)

	for i, result := range fields {
		fmt.Fprintf(&body, "\tif len(items) > %d {\n\t\tif err := %s.Unmarshal(items[%d], &s.%s); err != nil {\n"+
			"\t\t\treturn err\n\t\t}\n\t}\n", i, g.json(), i, result.name)
	}

	if restType != "" {
		fmt.Fprintf(&body, "\tfor _, item := range items[min(len(items), %d):] {\n\t\tvar value %s\n"+
			"\t\tif err := %s.Unmarshal(item, &value); err != nil {\n\t\t\treturn err\n\t\t}\n"+
			"\t\ts.Rest = append(s.Rest, value)\n\t}\n", len(fields), restType, g.json())
	}

	body.WriteString("\treturn nil\n}")

	return body.String()
}

func indent(text string) string {
	if text == "" {
		return ""
	}

	lines := strings.Split(strings.TrimSuffix(text, "\n"), "\n")

	return "\t" + strings.Join(lines, "\n\t") + "\n"
}
