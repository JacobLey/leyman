import type { geneverFile } from './genever-file.js';
import { Converter, defaultTypedMinItems } from './lib/convert.js';
import { openApiDialect } from './lib/openapi.js';
import { printDoc, printType } from './lib/print.js';
import { defaultBaseUri } from './lib/resources.js';

/**
 * @import { GeneverError } from './lib/errors.js'
 */

/**
 * Options for {@link genever}.
 */
export interface GeneverOptions {
    /**
     * URI the schema was read from, which relative `$id`s and `$ref`s resolve against.
     * A `$ref` to a resource not in the document is not supported: use {@link geneverFile},
     * which bundles referenced files and URLs into the document first.
     *
     * @default a placeholder, so only references within the document resolve
     */
    baseUri?: string;
    /**
     * Name of the root schema's type. Not used for an OpenAPI document, which has no root schema.
     *
     * @default 'Schema'
     */
    name?: string;
    /**
     * Read the schema as an OpenAPI 3.0 schema, which allows `nullable` and `example`.
     * Not used for an OpenAPI document, whose `openapi` version decides.
     *
     * @default false
     */
    openApi30?: boolean;
    /**
     * With an OpenAPI document, also generate `OperationRequest<Id>`: what a server's handler gets once a
     * validator that fills in defaults (such as Ajv's `useDefaults`) has run, so parameters whose schema has a
     * `default` are always there. Only parameters: request bodies are as sent.
     *
     * @default false
     */
    parameterDefaults?: boolean;
    /**
     * Fail on schemas that are valid JSON Schema, but likely mistakes, such as unknown keywords.
     *
     * @default true
     */
    strict?: boolean;
    /**
     * Largest `minItems` typed as that many required items: `minItems: 1` is `[T, ...T[]]`.
     * Larger values are a plain array, as long tuples are hard to read and build. `0` turns it off.
     * The default matches Juniper.
     *
     * @default 3
     */
    typedMinItems?: number;
}

const header = '// Generated by genever. Do not edit by hand, regenerate it instead.';

/**
 * Generate TypeScript types from a JSON Schema, or an OpenAPI document.
 *
 * The root schema, and each of its definitions (`$defs`), becomes an exported type.
 * For an OpenAPI 3.0 or 3.1 document (with an `openapi` version), each of its `components.schemas` does.
 * The returned source is valid, but not formatted.
 *
 * @param schema - parsed JSON Schema, or OpenAPI document
 * @param [options] - optional
 * @param [options.baseUri] - URI the schema was read from, which relative references resolve against
 * @param [options.name] - name of the root schema's type, defaults to `Schema`
 * @param [options.openApi30] - read the schema as an OpenAPI 3.0 schema
 * @param [options.parameterDefaults] - also generate `OperationRequest`, with parameters' defaults filled in
 * @param [options.strict] - fail on likely mistakes in the schema, defaults to `true`
 * @param [options.typedMinItems] - largest `minItems` typed as required items, defaults to `3`
 * @returns TypeScript source
 * @throws {GeneverError} if the schema is invalid, breaks a strict mode rule, or is not supported
 */
export const genever = (schema: unknown, options: GeneverOptions = {}): string => {
    const documentDialect = openApiDialect(schema);
    const converter = new Converter(schema, {
        baseUri: options.baseUri ?? defaultBaseUri,
        dialect: documentDialect ?? (options.openApi30 ? 'openapi-3.0' : 'draft-2020-12'),
        parameterDefaults: options.parameterDefaults ?? false,
        strict: options.strict ?? true,
        typedMinItems: options.typedMinItems ?? defaultTypedMinItems,
    });
    const types = documentDialect
        ? converter.convertDocument()
        : converter.convert(options.name ?? 'Schema');

    return `${[
        header,
        ...types.map(
            ({ doc, exported = true, name, parameters = '', type }) =>
                `${printDoc(doc, '')}${exported ? 'export ' : ''}type ${name}${parameters} = ${typeof type === 'string' ? type : printType(type)};`
        ),
    ].join('\n\n')}\n`;
};
