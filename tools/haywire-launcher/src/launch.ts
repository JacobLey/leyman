import type { Main } from 'entry-script';
import type {
    ClassToConstructable,
    Container,
    GenericContainer,
    GenericHaywireId,
    HaywireIdType,
    IsClass,
    NonExtendable,
    OutputHaywireId,
} from 'haywire';
import EntryScript from 'entry-script';
import { identifier } from 'haywire';

export interface WrapperMain extends Main {
    getOriginal: () => Promise<Main>;
}

/**
 * Error messages for each failed check, shown by TypeScript when `launch()` is called with
 * arguments that can't work.
 */
interface LaunchMessages {
    containerDoesNotOutputEntryScript: 'Error: the container has no binding for EntryScript. Pass your entry class or its id instead, e.g. launch(container, MyCli).';
    containerDoesNotOutputId: 'Error: the container has no binding for this id.';
    idIsNotMain: "Error: the id's type has no main(argv: string[]): Promise<void> method.";
    notAContainer: 'Error: launch() needs a haywire container, from createContainer().';
}

/**
 * `unknown` when there are no failures, otherwise an object requiring their messages.
 * Intersected with a parameter, so an invalid argument fails with a readable message, while the
 * parameter's generic stays inferable.
 *
 * @template Failures - keys of failed checks, `never` when valid
 */
type Invalid<Failures extends keyof LaunchMessages> = [Failures] extends [never]
    ? unknown
    : { error: LaunchMessages[Failures] };

type EntryContainerFailures<C extends GenericContainer> =
    C extends Container<infer U>
        ? [
              NonExtendable<
                  EntryScript,
                  ClassToConstructable<typeof EntryScript>['construct'],
                  null,
                  false,
                  false,
                  false
              >,
          ] extends U
            ? never
            : 'containerDoesNotOutputEntryScript'
        : 'notAContainer';
type EntryLauncher = <C extends GenericContainer>(
    container: C & Invalid<EntryContainerFailures<C>>
) => WrapperMain;

/**
 * Id for what is passed to `launch()`: an id as is, or a class's id.
 *
 * @template IdOrClass - id or class passed to `launch()`
 */
type IdOf<IdOrClass> = IdOrClass extends GenericHaywireId
    ? IdOrClass
    : IdOrClass extends IsClass
      ? ClassToConstructable<IdOrClass>
      : never;

type IdContainerFailures<C extends GenericContainer, Id extends GenericHaywireId> =
    | (C extends Container<infer O>
          ? [
                NonExtendable<
                    NonNullable<HaywireIdType<OutputHaywireId<Id>>>,
                    Id['construct'],
                    Id['annotations']['named'],
                    false,
                    false,
                    false
                >,
            ] extends O
              ? never
              : 'containerDoesNotOutputId'
          : 'notAContainer')
    | (NonNullable<HaywireIdType<OutputHaywireId<Id>>> extends Main ? never : 'idIsNotMain');
/**
 * Options for `launch()`.
 */
export interface LaunchOptions {
    /**
     * Dispose the container (`container.disposeAsync()`) once `main()` resolves or rejects, or when getting the
     * instance fails. Defaults to `false`, for a `main()` that returns while what it started (like a server) keeps running.
     *
     * If disposing fails after `main()` rejected, the script rejects with a `SuppressedError` of both, as `await using` does.
     */
    dispose?: boolean;
}

type IdLauncher = <C extends GenericContainer, IdOrClass extends GenericHaywireId | IsClass>(
    container: C,
    id: IdOrClass & Invalid<IdContainerFailures<C, IdOf<IdOrClass>>>,
    options?: LaunchOptions
) => WrapperMain;

export const launch = ((
    container: AsyncDisposable & {
        getAsync: (val: unknown) => Promise<Main>;
    },
    id = EntryScript,
    { dispose = false }: LaunchOptions = {}
): WrapperMain =>
    /**
     * Anonymous class to be picked up as a subclass of EntryScript.
     */
    class extends EntryScript {
        /**
         * Get the Main implemenation that was generated by container.
         *
         * @returns Main implementation
         */
        public static async getOriginal(): Promise<Main> {
            return container.getAsync(identifier(id).baseId());
        }
        public static override async main(argv: string[]): Promise<void> {
            if (!dispose) {
                const main = await this.getOriginal();
                await main.main(argv);
                return;
            }
            // What `await using` does, written out: swc would compile it to imports from `@swc/helpers`
            try {
                const main = await this.getOriginal();
                await main.main(argv);
            } catch (err) {
                try {
                    await container[Symbol.asyncDispose]();
                } catch (disposeErr) {
                    throw new SuppressedError(
                        disposeErr,
                        err,
                        'Disposing the container failed, after main() failed'
                    );
                }
                throw err;
            }
            await container[Symbol.asyncDispose]();
        }
    }) as EntryLauncher & IdLauncher;
