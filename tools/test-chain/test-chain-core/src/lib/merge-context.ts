import { HookContextError } from './errors.js';

/**
 * Context before any hook has added to it.
 */
// eslint-disable-next-line @typescript-eslint/no-generated-empty-object-type -- `{}` is intended: every hook merges its additional context into this.
export type EmptyContext = NonNullable<unknown>;

export type AllowableAdditionalContext = object | null | undefined | void;

/**
 * Values with no own properties to merge, that types can tell apart from a plain object.
 */
type NotContext =
    | Date
    | ReadonlyMap<unknown, unknown>
    | ReadonlySet<unknown>
    | RegExp
    | readonly unknown[]
    | ((...args: never) => unknown);

/**
 * Intersect with a hook's return type to reject values that are not plain objects, such as arrays and functions.
 *
 * Types can't tell a class instance from a plain object, so those are only rejected at runtime, with a
 * `HookContextError`.
 *
 * @template Additional - type returned by the hook, optionally wrapped in a promise
 */
export type CheckedAdditionalContext<Additional> = [
    Extract<Awaited<Additional>, NotContext>,
] extends [never]
    ? unknown
    : { returnPlainObjectFromHook: never };
export type MergeContext<
    Existing extends object,
    Additional extends AllowableAdditionalContext,
> = Additional extends object
    ? {
          [K in keyof (Additional & Existing)]: (Additional & Existing)[K];
      }
    : Existing;

const describe = (value: unknown): string => {
    if (Array.isArray(value)) {
        return 'an array';
    }
    if (typeof value === 'object') {
        const type: unknown = (value as { constructor?: unknown }).constructor;
        return type !== Object && typeof type === 'function' && type.name !== ''
            ? `an instance of ${type.name}`
            : 'an object with a prototype';
    }
    return typeof value === 'function' ? 'a function' : `a ${typeof value}`;
};

/**
 * Assert a hook returned context that can be merged: a plain object (prototype `Object.prototype` or `null`), or
 * `undefined`/`null` for no context.
 *
 * @param additional - value returned by the hook
 * @returns the context, or `undefined` for none
 * @throws {HookContextError} if the value is anything else
 */
export const toAdditionalContext = (additional: unknown): object | undefined => {
    if (additional === undefined || additional === null) {
        return undefined;
    }
    if (typeof additional === 'object') {
        const prototype: unknown = Object.getPrototypeOf(additional);
        if (prototype === null || prototype === Object.prototype) {
            return additional;
        }
    }
    throw new HookContextError(describe(additional));
};

/**
 * Combine incoming existing context with the value generated by the hook.
 *
 * If hook returns a falsy value, the value is ignored and the existing
 * value is returned untouched.
 *
 * @param existingProm - promise of context generated by previous hooks
 * @param additionalProm - promise of context generated by current hook
 * @returns promise of merged contexts
 */
export const mergeContexts = async <
    Existing extends object,
    Additional extends AllowableAdditionalContext,
>(
    /**
     * Existing context, optionally wrapped in a promise
     */
    existingProm: Existing | Promise<Existing>,
    /**
     * Context returned by hook, optionally wrapped in a promise
     */
    additionalProm: Additional | Promise<Additional>
): Promise<MergeContext<Existing, Awaited<Additional>>> => {
    const [existing, additional] = await Promise.all([existingProm, additionalProm]);

    return additional
        ? ({ ...existing, ...additional } as MergeContext<Existing, Awaited<Additional>>)
        : (existing as MergeContext<Existing, Awaited<Additional>>);
};
